# ------------------------------------------------------------
# 知识点 8：if 条件判断（满足条件才执行，注意冒号和缩进）
# ------------------------------------------------------------
print("=" * 50)
print("知识点 8：if 条件判断")
print("=" * 50)
score = 75
if score >= 90:                 # if 后面写条件，结尾必须有冒号 :
    print("优秀")                # 满足条件时执行的代码要缩进（建议 4 个空格）
elif score >= 60:               # elif = else if，“否则如果”
    print("及格")
else:                           # 以上条件都不满足时执行
    print("不及格")
# Python 靠“缩进”区分代码属于哪个分支，大括号 {} 都不用写


# ------------------------------------------------------------
# 知识点 9：循环（让代码重复执行）
# ------------------------------------------------------------
print("=" * 50)
print("知识点 9：循环")
print("=" * 50)

# for 循环：适合“知道要重复几次”，range(3) 产生 0、1、2
for i in range(3):
    print("for 循环第", i, "次")

# range(1, 4) 产生 1、2、3（含头不含尾）
for i in range(1, 4):
    print("数数：", i)

# while 循环：适合“满足条件就一直重复”
count = 3
while count > 0:
    print("倒计时：", count)
    count = count - 1    # 别忘了改变条件，否则会无限循环！
print("发射！")

# break：立即跳出循环；continue：跳过本次，继续下一次
for i in range(1, 6):
    if i == 3:
        continue         # 跳过数字 3
    if i == 5:
        break            # 到 5 就结束
    print("循环中的 i =", i)


