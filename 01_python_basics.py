# ------------------------------------------------------------
# 知识点 6：运算符
# ------------------------------------------------------------
print("=" * 50)
print("知识点 6：运算符")
print("=" * 50)
print("7 + 2 =", 7 + 2)    # 加
print("7 - 2 =", 7 - 2)    # 减
print("7 * 2 =", 7 * 2)    # 乘
print("7 / 2 =", 7 / 2)    # 除（结果总是小数 3.5）
print("7 // 2 =", 7 // 2)  # 整除（扔掉小数部分，得 3）
print("7 % 2 =", 7 % 2)    # 取余数（7 除以 2 余 1）
print("7 ** 2 =", 7 ** 2)  # 幂运算（7 的 2 次方 = 49）

# 比较运算符：结果是 True 或 False
print("3 > 2 的结果：", 3 > 2)
print("3 == 3 的结果：", 3 == 3)   # == 是“判断是否相等”，= 是赋值，两者完全不同！
print("3 != 3 的结果：", 3 != 3)   # != 是“判断是否不相等”

# 逻辑运算符：and（并且）、or（或者）、not（取反）
print("True and False =", True and False)
