# ------------------------------------------------------------
# 知识点 6：列表推导式（Python 最有特色的“一行造列表”）
# ------------------------------------------------------------
print("=" * 50)
print("知识点 6：列表推导式")
print("=" * 50)

# 普通写法：把 1~5 的平方放进列表
squares = []
for n in range(1, 6):
    squares.append(n ** 2)
print("普通写法：", squares)

# 推导式写法（同一回事，浓缩成一行）
# 读法：对 range(1,6) 里的每个 n，收集 n ** 2
squares2 = [n ** 2 for n in range(1, 6)]
print("推导式写法：", squares2)

# 带条件的推导式：只收集偶数
evens = [n for n in range(1, 11) if n % 2 == 0]
print("1~10 的偶数：", evens)

# 实战：把一批字符串统一变大写
names = ["alice", "bob", "carol"]
print("统一大写：", [name.upper() for name in names])
print("统一大写：", names)

# ------------------------------------------------------------
# 知识点 7：嵌套数据结构（真实数据的样子）
# 字典装在列表里 —— 每条记录是一个字典，多条记录组成列表
# ------------------------------------------------------------
print("=" * 50)
print("知识点 7：嵌套结构（列表装字典）")
print("=" * 50)
students = [
    {"name": "小明", "age": 18, "score": 88},
    {"name": "小红", "age": 17, "score": 95},
    {"name": "小刚", "age": 18, "score": 72},
]
print("全部学生：", students)

# 访问：先选列表中的第几条（下标），再选字典中的哪个键
print("第 1 个学生的姓名：", students[0]["name"])
print("第 2 个学生的分数：", students[1]["score"])

# 遍历：每次循环 stu 就是一个字典
print("成绩榜：")
for stu in students:
    print(f"{stu['name']} - {stu['age']}岁 - {stu['score']}分")

# 添加一条新记录（append 一个新字典）
students.append({"name": "小李", "age": 19, "score": 60})
print("添加后共", len(students), "人")

# 综合：用推导式找出所有及格学生的姓名
passed = [stu["name"] for stu in students if stu["score"] >= 80]
print("80 分以上的同学：", passed)

# 综合：用循环求全班平均分
total_score = 0
for stu in students:
    total_score = total_score + stu["score"]
print("全班平均分：", total_score / len(students))


