# ------------------------------------------------------------
# 知识点 1：字符串切片（从文字里“截取”一段）
# 语法： s[起点:终点]   规则：含起点，不含终点（和 range 一样！）
# ------------------------------------------------------------
print("=" * 50)
print("知识点 1：字符串切片")
print("=" * 50)
s = "abcdef"
print("完整字符串：", s)
print("s[0:3] =", s[0:3])     # 取下标 0、1、2 → abc（不含 3）
print("s[2:5] =", s[2:5])     # 取下标 2、3、4 → cde
print("s[:4]  =", s[:4])      # 起点省略 = 从头开始 → abcd
print("s[3:]  =", s[3:])      # 终点省略 = 一直取到末尾 → def
print("s[-1]  =", s[-1])      # 负数下标：-1 是倒数第 1 个 → f
print("s[-3:] =", s[-3:])     # 倒数 3 个 → def
print("s[::2] =", s[::2])     # 第三个数字是“步长”：每隔 1 个取 → ace
print("s[::-1] =", s[::-1])   # 步长 -1：倒序！这是最常用的反转技巧 → fedcba

phone = "13812345678"
print("手机号前 3 位：", phone[:3])
print("手机号后 4 位：", phone[-4:])


