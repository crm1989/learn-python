# 知识点 8：enumerate —— 遍历列表时同时拿到“编号”和“内容”
# 比上一课手动维护 index 计数器更优雅
# ------------------------------------------------------------
print("=" * 50)
print("知识点 8：enumerate 自动编号")
print("=" * 50)
fruits = ["苹果", "香蕉", "橘子"]
for index, fruit in enumerate(fruits):
    print(f"{index + 1}. {fruit}")     # index 从 0 开始，+1 显示成人类习惯的 1、2、3


