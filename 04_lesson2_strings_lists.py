# 知识点 5：列表常用方法（增、删、排序）
# ------------------------------------------------------------
print("=" * 50)
print("知识点 5：列表常用方法")
print("=" * 50)
bag = ["书", "笔"]
bag.append("水杯")            # 末尾添加一个
print("append 后：", bag)
bag.insert(0, "钥匙")         # 在指定下标处插入
