# -*- coding: utf-8 -*-
# ============================================================
# 实战项目：命令行通讯录
# 运行方法： py 03_contacts_project.py
#
# 功能菜单：
#   1. 添加联系人（姓名 -> 电话）
#   2. 查询联系人（输入姓名，显示电话）
#   3. 删除联系人（输入姓名，从通讯录移除）
#   4. 显示全部（按编号列出所有人）
#   5. 退出程序
#
# 数据结构：用一个字典 contacts 保存全部数据
#   key   = 姓名（字符串）
#   value = 电话（字符串，电话可能含 0 开头或横线，不要转成数字）
#
# 做题前：记得把 CUE 休眠（右下角 CUE 图标 -> 休眠 30 分钟）
# 做完后：运行程序，手动把 5 个功能都点一遍测试，再发给我批改
# ============================================================

contacts = {}   # 通讯录一开始是空的

# while True 是一个“永远循环”，只有在循环里遇到 break 才会结束
while True:
    # ---------- 显示菜单 ----------
    print()
    print("===== 我的通讯录 =====")
    print("1. 添加联系人")
    print("2. 查询联系人")
    print("3. 删除联系人")
    print("4. 显示全部")
    print("5. 退出")

    choice = input("请输入操作编号（1-5）：")

    # ---------- 功能 1：添加 ----------
    if choice == "1":
        # 提示：
        # 1. 用两次 input 分别拿到姓名和电话
        # 2. 进阶要求：如果姓名已经在 contacts 里，
        #    先打印“该联系人已存在，电话将被更新”再覆盖
        #    （用 if 名字 in contacts 判断）
        # 3. 用 contacts[名字] = 电话 存入
        # 4. 存完打印“添加成功”
        name = input("输入您的姓名：")
        phone = input("输入您的电话：")
        if name in contacts:
            print("该联系人已存在，电话将被更新")
        contacts[name] = phone
        print("添加成功")

    # ---------- 功能 2：查询 ----------
    elif choice == "2":
        # 提示：
        # 1. input 拿到要查询的姓名
        # 2. 用 if 姓名 in contacts 判断是否存在
        #    存在：打印姓名和电话（可以用 f-string：f"{name} 的电话是 {contacts[name]}"）
        #    不存在：打印“查无此人”
        name = input("要查询的姓名")
        if name in contacts:
            print(f"{name}的电话是{contacts[name]}")
        else:
            print("查无此人")

    # ---------- 功能 3：删除 ----------
    elif choice == "3":
        # 提示：
        # 1. input 拿到要删除的姓名
        # 2. 必须先判断存在再删！
        #    直接删除不存在的键会报 KeyError（还记得第 13 题越界的教训吗）
        # 3. 删除语法： del contacts[姓名]
        #    存在：删除后打印“删除成功”
        #    不存在：打印“查无此人，无法删除”
        name = input("要删除的姓名")
        if name in contacts:
            del contacts[name]
            print("删除成功")
        else:
            print("查无此人，无法删除")

    # ---------- 功能 4：显示全部 ----------
    elif choice == "4":
        # 提示：
        # 1. 先判断通讯录是否为空： if len(contacts) == 0: 打印“通讯录是空的”
        # 2. 不为空时，用 for name, phone in contacts.items(): 遍历
        #    打印出每个人，例如： 1. 小明 - 13800000000
        # 3. 编号怎么来？在循环外面建一个 index = 1，
        #    每打印一个人就 index = index + 1
        if len(contacts) != 0:
            index = 0
            for name, phone in contacts.items():
                index += 1
                print(f"{index}. 姓名:{name}电话:{phone}")
        else:
            print("通讯录是空的")

    # ---------- 功能 5：退出 ----------
    elif choice == "5":
        print("程序已退出，再见！")
        break   # break 跳出 while True，程序结束

    # ---------- 输入了 1-5 以外的内容 ----------
    else:
        print("没有这个选项，请输入 1 到 5 之间的数字")

# 自我测试清单（全部通过才算完成）：
# [ ] 添加两个人后，选 4 能看到两个人，编号分别是 1 和 2
# [ ] 添加已存在的姓名时，会提示更新，且电话被新电话覆盖
# [ ] 查询存在的人显示电话；查询不存在的人显示“查无此人”，程序不崩溃
# [ ] 删除后再选 4，那个人消失了
# [ ] 删除不存在的人，显示提示而不是报 KeyError
# [ ] 输入 9 或 abc 等无效选项时，提示重新输入且程序继续运行
# [ ] 选 5 程序正常结束
